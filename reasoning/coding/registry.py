"""AXEN Language Registry.

Centralized specifications for all 37 supported programming languages.
Provides metadata on syntax families, ecosystem, toolchains, and real local
runtime detection without fabricating tool availability.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple


@dataclass(frozen=True)
class LanguageSpec:
    name: str
    slug: str
    aliases: tuple[str, ...]
    extensions: tuple[str, ...]
    syntax_family: str
    category: str
    primary_uses: tuple[str, ...]
    ecosystem: tuple[str, ...]
    compilers_or_interpreters: tuple[str, ...]
    package_managers: tuple[str, ...]
    formatters: tuple[str, ...]
    linters: tuple[str, ...]
    test_frameworks: tuple[str, ...]
    debuggers: tuple[str, ...]
    static_analyzers: tuple[str, ...]
    can_execute: bool
    can_syntax_check: bool

    def check_runtime(self) -> Tuple[bool, Optional[str]]:
        """Inspect the local environment to detect if an actual runtime/compiler is installed."""
        for binary in self.compilers_or_interpreters:
            # Handle commands with flags or multiple components
            cmd = binary.split()[0]
            resolved = shutil.which(cmd)
            if resolved:
                return True, resolved
        return False, None

    def to_dict(self) -> Dict[str, Any]:
        installed, path = self.check_runtime()
        return {
            "name": self.name,
            "slug": self.slug,
            "aliases": list(self.aliases),
            "extensions": list(self.extensions),
            "syntax_family": self.syntax_family,
            "category": self.category,
            "primary_uses": list(self.primary_uses),
            "ecosystem": list(self.ecosystem),
            "compilers_or_interpreters": list(self.compilers_or_interpreters),
            "package_managers": list(self.package_managers),
            "formatters": list(self.formatters),
            "linters": list(self.linters),
            "test_frameworks": list(self.test_frameworks),
            "debuggers": list(self.debuggers),
            "static_analyzers": list(self.static_analyzers),
            "can_execute": self.can_execute,
            "can_syntax_check": self.can_syntax_check,
            "runtime_available": installed,
            "runtime_path": path,
        }


