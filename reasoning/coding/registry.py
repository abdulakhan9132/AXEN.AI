class LanguageRegistry:
    """Registry managing all 37 languages with indexed lookups."""

    def __init__(self) -> None:
        self._languages: dict[str, LanguageSpec] = {}
        self._by_alias: dict[str, LanguageSpec] = {}
        self._by_ext: dict[str, list[LanguageSpec]] = {}

        for lang in _LANGUAGES_DATA:
            self._languages[lang.slug] = lang
            self._by_alias[lang.name.lower()] = lang
            self._by_alias[lang.slug] = lang
            for alias in lang.aliases:
                self._by_alias[alias.lower()] = lang
            for ext in lang.extensions:
                ext_list = self._by_ext.setdefault(ext.lower(), [])
                if lang not in ext_list:
                    ext_list.append(lang)

    def get(self, name_or_alias: str) -> Optional[LanguageSpec]:
        """Look up a language by name, slug, or alias."""
        clean = name_or_alias.strip().lower()
        return self._by_alias.get(clean)

    def get_by_extension(self, extension: str) -> list[LanguageSpec]:
        """Look up candidate languages by file extension."""
        clean = extension.strip().lower()
        if not clean.startswith("."):
            clean = "." + clean
        return self._by_ext.get(clean, [])

    def list_all(self) -> list[LanguageSpec]:
        """Return all 37 languages sorted by name."""
        return sorted(self._languages.values(), key=lambda l: l.name)

    def count(self) -> int:
        return len(self._languages)


_DEFAULT_REGISTRY = LanguageRegistry()


def get_language_registry() -> LanguageRegistry:
    return _DEFAULT_REGISTRY
